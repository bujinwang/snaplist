/**
 * E6-T4 — On-model.
 *
 * Flow: (paywall if not Pro) → (one-time VERBATIM consent gate) → model-card
 * picker + render slot. The consent text is quoted exactly from
 * `docs/templates/consent-copy.md` v1.0 (E9-T3); the `vton` request cannot be
 * made until the seller has acknowledged it.
 *
 * The on-model slot reads `on_model_state` from the mock vton job and shows
 * not requested / rendering / ready; a failed render leaves the slot untouched
 * and shows §6 copy. It lives on its own route so it NEVER blocks review
 * (ADR-004). `paywall_impression` is emitted by <PaywallCard> with the
 * deterministic mock variant (the real variant is server-assigned, E8-T4).
 */

import React, { useMemo, useState } from "react";
import {
  ActivityIndicator,
  Pressable,
  StyleSheet,
  Text,
  View,
} from "react-native";

import { useDrafts } from "../offline/DraftsProvider";
import {
  acceptOnModelConsent,
  hasAcceptedOnModelConsent,
} from "../offline/consent";
import { PaywallCard } from "./Paywall";
import { failureCopy } from "../lib/failureCopy";

interface ModelCard {
  id: string;
  name: string;
}

const MODEL_CARDS: ReadonlyArray<ModelCard> = [
  { id: "studio_a", name: "Studio A" },
  { id: "lifestyle_b", name: "Lifestyle B" },
  { id: "flatlay_c", name: "Flat Lay C" },
];

/**
 * Verbatim from `docs/templates/consent-copy.md` v1.0 (the BEGIN/END block).
 * Do NOT reword — E9-T3 requires the app to quote it exactly. Bump the version
 * in `offline/consent.ts` and this file only after legal review.
 */
const ON_MODEL_CONSENT_V1 = `Before we create your on-model shot:

• Your garment will be shown on a model image that is computer-generated (synthetic).
• The model image is licensed to SnapList for this purpose.
• No real person's photograph or likeness is used to create your on-model image.
• The on-model image is generated by AI and is for illustrating how the garment may look on a
  body. It is not a photograph of a real person wearing your item.

By continuing, you confirm you understand the above and consent to SnapList generating this
on-model image from your garment photo. You can skip this step at any time — your listing works
without it.`;

export function OnModelScreen(): JSX.Element {
  const drafts = useDrafts();

  const reviewable = useMemo(
    () =>
      drafts.items.filter((it) => it.status === "done" && !it.blocked_by_quota),
    [drafts.items],
  );

  const [modelId, setModelId] = useState<string>(MODEL_CARDS[0]?.id ?? "studio_a");
  const [selectedItemId, setSelectedItemId] = useState<string | null>(null);
  const [consented, setConsented] = useState<boolean>(() =>
    hasAcceptedOnModelConsent(),
  );

  const selectedItem =
    reviewable.find((it) => it.item_id === selectedItemId) ?? reviewable[0] ?? null;

  const onModelState = selectedItem?.on_model_state ?? "not_requested";
  const vtonFailed = selectedItem?.vton_status === "failed";

  const render = (): void => {
    if (selectedItem) void drafts.requestOnModel(selectedItem.item_id, modelId);
  };

  const acceptConsent = (): void => {
    acceptOnModelConsent();
    setConsented(true);
  };

  return (
    <View style={styles.body}>
      <Text style={styles.h}>On-model</Text>

      {!drafts.isPro ? (
        <PaywallCard trigger="on_model" onUpgrade={drafts.upgradeToPro} />
      ) : null}

      {/* E9-T3: the vton job must not be enqueued before this is acknowledged. */}
      {drafts.isPro && !consented ? (
        <ConsentCard onAccept={acceptConsent} />
      ) : null}

      {!drafts.isPro || !consented ? null : reviewable.length === 0 ? (
        <Text style={styles.empty}>
          Capture and review an item first, then come back to put it on a model.
        </Text>
      ) : (
        <View style={styles.content}>
          {/* Item selector */}
          <Text style={styles.sectionTitle}>Item</Text>
          <View style={styles.optionRow}>
            {reviewable.map((it, idx) => (
              <Pressable
                key={it.item_id}
                style={({ pressed }) => [
                  styles.opt,
                  selectedItem?.item_id === it.item_id && styles.optSelected,
                  pressed && styles.pressed,
                ]}
                onPress={() => setSelectedItemId(it.item_id)}
              >
                <Text
                  style={
                    selectedItem?.item_id === it.item_id
                      ? styles.optTextSelected
                      : styles.optText
                  }
                >
                  #{idx + 1}
                </Text>
              </Pressable>
            ))}
          </View>

          {/* Model card picker */}
          <Text style={styles.sectionTitle}>Model</Text>
          <View style={styles.cards}>
            {MODEL_CARDS.map((m) => (
              <Pressable
                key={m.id}
                style={({ pressed }) => [
                  styles.card,
                  modelId === m.id && styles.cardSelected,
                  pressed && styles.pressed,
                ]}
                onPress={() => setModelId(m.id)}
              >
                <View style={styles.cardThumb} />
                <Text style={styles.cardName}>{m.name}</Text>
              </Pressable>
            ))}
          </View>

          {/* On-model slot — never blocks review (ADR-004) */}
          <Text style={styles.sectionTitle}>Render</Text>
          <View style={styles.slot}>
            {onModelState === "not_requested" ? (
              <Text style={styles.slotText}>Not requested yet</Text>
            ) : null}
            {onModelState === "rendering" ? (
              <View style={styles.slotCenter}>
                <ActivityIndicator color="#151515" />
                <Text style={styles.slotText}>Rendering…</Text>
              </View>
            ) : null}
            {onModelState === "ready" && selectedItem ? (
              <View style={styles.slotCenter}>
                <View
                  style={[
                    styles.slotImg,
                    { backgroundColor: selectedItem.prettifiedColor },
                  ]}
                />
                <Text style={styles.slotText}>Ready on {modelId}</Text>
              </View>
            ) : null}
          </View>

          {vtonFailed && selectedItem ? (
            <View style={styles.errorBox}>
              <Text style={styles.errorTitle}>
                {failureCopy(selectedItem.vton_reason_code).title}
              </Text>
              <Text style={styles.errorBody}>
                {failureCopy(selectedItem.vton_reason_code).body}
              </Text>
            </View>
          ) : null}

          <Pressable
            style={({ pressed }) => [
              styles.renderBtn,
              pressed && styles.pressed,
            ]}
            onPress={render}
          >
            <Text style={styles.renderBtnText}>Put it on the model</Text>
          </Pressable>
        </View>
      )}
    </View>
  );
}

function ConsentCard(props: { onAccept: () => void }): JSX.Element {
  return (
    <View style={styles.consent}>
      <Text style={styles.consentTitle}>Before your first on-model shot</Text>
      <Text style={styles.consentBody}>{ON_MODEL_CONSENT_V1}</Text>
      <Pressable
        style={({ pressed }) => [styles.consentBtn, pressed && styles.pressed]}
        onPress={props.onAccept}
      >
        <Text style={styles.consentBtnText}>I understand — continue</Text>
      </Pressable>
      <Text style={styles.consentNote}>
        Shown once per account. Quoted verbatim from docs/templates/consent-copy.md v1.0.
      </Text>
    </View>
  );
}

